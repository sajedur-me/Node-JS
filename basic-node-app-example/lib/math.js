// কোডের ব্যাখ্যা: এই কোডটি একটি সহজ ম্যাথ লাইব্রেরি যা একটি ফাংশন প্রদান করে যা নির্দিষ্ট সীমার মধ্যে একটি র্যান্ডম সংখ্যা তৈরি করে। `getRandomNumber` ফাংশনটি দুটি প্যারামিটার গ্রহণ করে, `min` এবং `max`, যা র্যান্ডম সংখ্যার ন্যূনতম এবং সর্বাধিক সীমা নির্ধারণ করে। ফাংশনটি প্রথমে এই প্যারামিটারগুলিকে যাচাই করে যে তারা সংখ্যা কিনা, যদি না হয় তবে তাদের ডিফল্ট মান 0 সেট করে। তারপর এটি `Math.random()` ব্যবহার করে একটি র্যান্ডম সংখ্যা তৈরি করে যা নির্দিষ্ট সীমার মধ্যে থাকে এবং এটি পূর্ণসংখ্যা হিসাবে রিটার্ন করে। এই লাইব্রেরিটি `module.exports` ব্যবহার করে রপ্তানি করা হয়, যাতে এটি অন্যান্য ফাইল থেকে আমদানি করা যায় এবং ব্যবহার করা যায়। 
const math = {};

math.getRandomNumber = function getRandomNumber(min, max) {
    let minimum = min;
    let maximum = max;

    minimum = typeof minimum === 'number' ? minimum : 0;
    maximum = typeof maximum === 'number' ? maximum : 0;
    return Math.floor(Math.random() * (maximum - minimum + 1) + minimum);
};

module.exports = math;


