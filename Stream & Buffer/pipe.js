
// কোডের ব্যাখ্যা: এই কোডটি একটি HTTP সার্ভার তৈরি করে যা ক্লায়েন্টের অনুরোধে একটি বড় টেক্সট ফাইল পাঠায়। `fs.createReadStream` ব্যবহার করে ফাইলটি স্ট্রিম আকারে পড়া হয় এবং `pipe` মেথড ব্যবহার করে সরাসরি HTTP রেসপন্সে পাঠানো হয়। এটি মেমোরি ব্যবহারের দক্ষতা বাড়ায় কারণ পুরো ফাইলটি একবারে মেমোরিতে লোড করা হয় না। সার্ভারটি 3000 পোর্টে চলছে। যখন ক্লায়েন্ট এই সার্ভারে অনুরোধ করে, তখন `biggest-data.txt` ফাইলটি স্ট্রিম আকারে পাঠানো হয় এবং ক্লায়েন্ট সেই ডেটা রিসিভ করে। এই পদ্ধতিতে বড় ফাইলগুলি সহজেই পরিচালনা করা যায় কারণ এটি পুরো ফাইলটি একবারে মেমরিতে লোড করে না, বরং ছোট ছোট অংশে ডেটা পড়ে এবং পাঠানোর কাজ করে। এটি একটি কার্যকর এবং দক্ষ উপায় বড় ডেটা সেটগুলি পরিচালনা করার জন্য। 

const http = require('http');
const fs = require('fs');

const server = http.createServer((req, res) => {
    const myReadStream = fs.createReadStream(`${__dirname}/biggest-data.txt`, 'utf8');
    myReadStream.pipe(res);
    
});

server.listen(3000, () => {
    console.log('Server is running on port 3000');
});


