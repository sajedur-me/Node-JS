// ডিটেইলস : জাভাস্ক্রিপ্টে ইভেন্ট এমিটার হলো একটি কোর মডিউল যা ইভেন্ট-ড্রিভেন প্রোগ্রামিংয়ের জন্য ব্যবহৃত হয়। এটি একটি ইভেন্ট এমিটার অবজেক্ট তৈরি করে যা ইভেন্ট লিসেনার এবং ইভেন্ট ট্রিগার করার জন্য ফাংশন প্রদান করে। আপনি ইভেন্ট লিসেনার সেট করতে পারেন যা নির্দিষ্ট ইভেন্টের জন্য কাজ করবে, এবং পরে সেই ইভেন্টকে ট্রিগার করতে পারেন যাতে লিসেনারটি কার্যকর হয়।
const EventEmittre = require('events');
const myEvent = new EventEmittre();

myEvent.on('greet', (name) => { 
    console.log(`Hello, ${name}!`); 
});

myEvent.emit('greet', 'Sajed'); // এটি 'greet' ইভেন্টকে ট্রিগার করে এবং 'Sajed' নামটি পাস করে, যা ইভেন্ট লিসেনার দ্বারা গ্রহণ করা হবে এবং প্রিন্ট করা হবে  


// ডিটেইলস : জাভাস্ক্রিপ্টে মডিউল হলো একটি ফাইল যা কোডের একটি নির্দিষ্ট অংশকে ধারণ করে এবং অন্য ফাইল থেকে ইমপোর্ট করা যায়। মডিউল ব্যবহার করে আপনি কোডকে পুনঃব্যবহারযোগ্য এবং সংগঠিত করতে পারেন। আপনি একটি মডিউল তৈরি করতে পারেন যা একটি ক্লাস, ফাংশন, অবজেক্ট ইত্যাদি রপ্তানি করে, এবং পরে সেই মডিউলকে অন্য ফাইলে ইমপোর্ট করে ব্যবহার করতে পারেন।

const ExpEventFile = require('./exp-event-file'); 
const expEventFile = new ExpEventFile();

// 'ExpEventFile' ক্লাসটি 'exp-event-file.js' ফাইল থেকে ইমপোর্ট করা হয়েছে এবং একটি নতুন অবজেক্ট তৈরি করা হয়েছে। এখন আমরা এই অবজেক্টের মাধ্যমে ইভেন্ট লিসেনার সেট করতে পারি এবং ইভেন্ট ট্রিগার করতে পারি। 
expEventFile.on('farewell', (data) => {
    console.log(`Goodbye, ${data.name}! ${data.message}`); 
});

expEventFile.myFunction(); // এটি 'myFunction' মেথডকে কল করে, যা 'farewell' ইভেন্টকে ট্রিগার করবে এবং লিসেনারটি কার্যকর হবে





