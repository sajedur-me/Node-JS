//     console.log(data.toString()); // এটি ফাইলের কনটেন্টকে কনসোলে প্রিন্ট করে
// });


fs.readFile('myfile.txt', 'utf-8', (err, data) => { // এটি একটি ফাইল পড়ে এবং তার কনটেন্টকে কলব্যাক ফাংশনে রিটার্ন করে, এখানে 'utf-8' এনকোডিং ব্যবহার করা হয়েছে
    console.log(data); // এটি ফাইলের কনটেন্টকে কনসোলে প্রিন্ট করে
});