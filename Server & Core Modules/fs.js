// ডিটেইলস : জাভাস্ক্রিপ্টে ওএস মডিউল হলো একটি কোর মডিউল যা অপারেটিং সিস্টেম সম্পর্কিত তথ্য এবং ফাংশন প্রদান করে। এটি ব্যবহার করে আপনি সিস্টেমের প্ল্যাটফর্ম, হোম ডিরেক্টরি, সিপিইউ আর্কিটেকচার ইত্যাদি তথ্য পেতে পারেন। 
const os = require('os');

console.log(os.platform()); // এটি অপারেটিং সিস্টেমের প্ল্যাটফর্মকে রিটার্ন করে, যেমন: 'win32', 'darwin', 'linux' ইত্যাদি 
console.log(os.homedir()); // এটি ব্যবহারকারীর হোম ডিরেক্টরির পাথকে রিটার্ন করে
console.log(os.cpus()); // এটি সিপিইউ সম্পর্কিত তথ্যকে একটি অ্যারে আকারে রিটার্ন করে, যেখানে প্রতিটি অবজেক্টে সিপিইউ এর মডেল, স্পিড ইত্যাদি তথ্য থাকে


// ডিটেইলস : জাভাস্ক্রিপ্টে ফাইল সিস্টেম (fs) মডিউল হলো একটি কোর মডিউল যা ফাইল এবং ডিরেক্টরির সাথে কাজ করার জন্য বিভিন্ন ফাংশন প্রদান করে। এটি ব্যবহার করে আপনি ফাইল তৈরি করতে, পড়তে, লিখতে, মুছতে এবং অন্যান্য ফাইল অপারেশন করতে পারেন। 
const fs = require('fs');

// ফাইল তৈরি এবং লেখা synchronously. 
fs.writeFileSync('myfile.txt', 'Hello Programming'); // এটি একটি নতুন ফাইল তৈরি করে এবং তাতে নির্দিষ্ট টেক্সট লিখে
fs.appendFileSync('myfile.txt', ' Welcome to Node.js'); // এটি একটি বিদ্যমান ফাইলের শেষে নির্দিষ্ট টেক্সট যোগ করে


